// Generates the time-zone flags (ADR 0017):
//   - src/lib/zone-countries.ts: IANA zone → ISO 3166 country code, from tzdb's zone.tab
//   - public/flags/<cc>.webp: each country's flag at 40×30 (shown at 20×15), rendered from the
//     flag-icons SVGs (MIT) with Playwright's Chromium. Some SVGs are 100+ kB (coats of arms);
//     the WebPs are ~1 kB each and load only when a flag is on screen.
//
//   node scripts/flags.mjs
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ZONE_TAB = "https://raw.githubusercontent.com/eggert/tz/main/zone.tab";
const W = 40;
const H = 30;

const res = await fetch(ZONE_TAB);
if (!res.ok) throw new Error(`zone.tab: HTTP ${res.status}`);
const map = new Map();
for (const line of (await res.text()).split("\n")) {
	if (!line || line.startsWith("#")) continue;
	const [cc, , zone] = line.split("\t");
	map.set(zone, cc.toLowerCase());
}
const zones = [...map.keys()].sort();
const countries = [...new Set(map.values())].sort();

writeFileSync(
	path.join(root, "src/lib/zone-countries.ts"),
	`// Generated by scripts/flags.mjs from tzdb zone.tab. Do not edit by hand.
// IANA zone → ISO 3166-1 alpha-2 country code (lower case). Zones without a country (UTC, Etc/*) are absent.
export const ZONE_COUNTRY: Record<string, string> = {
${zones.map((z) => `\t${JSON.stringify(z)}: ${JSON.stringify(map.get(z))},`).join("\n")}
};

/** Countries with a flag image in public/flags/<cc>.webp. */
export const FLAG_COUNTRIES: ReadonlySet<string> = new Set(${JSON.stringify(countries)});
`,
);

const svgDir = path.join(root, "node_modules/flag-icons/flags/4x3");
const outDir = path.join(root, "public/flags");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const browser = await chromium.launch();
let bytes = 0;
try {
	const page = await browser.newPage();
	await page.setContent("<!doctype html><body></body>");
	for (const cc of countries) {
		const svg = readFileSync(path.join(svgDir, `${cc}.svg`), "utf8");
		const b64 = await page.evaluate(
			async ({ svg, W, H }) => {
				const img = new Image();
				img.src = `data:image/svg+xml;base64,${btoa(unescape(encodeURIComponent(svg)))}`;
				await img.decode();
				const c = document.createElement("canvas");
				c.width = W;
				c.height = H;
				const ctx = c.getContext("2d");
				ctx.imageSmoothingQuality = "high";
				ctx.drawImage(img, 0, 0, W, H);
				const url = c.toDataURL("image/webp", 0.9);
				return url.slice(url.indexOf(",") + 1);
			},
			{ svg, W, H },
		);
		const buf = Buffer.from(b64, "base64");
		bytes += buf.length;
		writeFileSync(path.join(outDir, `${cc}.webp`), buf);
	}
} finally {
	await browser.close();
}
console.log(`${zones.length} zones, ${countries.length} flags, ${Math.round(bytes / 1024)} kB total`);
